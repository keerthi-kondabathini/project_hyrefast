const { test, expect }           = require('../../utils/authFixture');
const { CandidatesPage }         = require('../../pages/CandidatesPage');
const testData                   = require('../../data/testData.json');
const path                       = require('path');

const FIX = path.resolve(__dirname, '../../', 'fixtures');
const PD  = path.join(FIX, 'resumes');

// ─── shared helpers ──────────────────────────────────────────────────────

/** Opens the Candidates view for the default test job and returns the URL + initial count. */
async function openCandidates(candidatesPage) {
  const jobTitle = testData.candidates.jobTitle;
  await test.step(`Open Candidates view for "${jobTitle}"`, async () => {
    await candidatesPage.searchAndOpenCandidates(jobTitle);
    await candidatesPage.assertApplicationsPageOpen(jobTitle);
  });
  const url = candidatesPage.getCandidatesPageUrl();
  const initialCount = await candidatesPage.getCandidateCount();
  return { url, initialCount, jobTitle };
}

// ══════════════════════════════════════════════════════════════════════════
//  TC_APP_001 — Resume upload flow (re-implemented end-to-end, plus
//  re-verification of the candidate opening the interview link)
//  Covers the "Resume upload flow" gap listed as 🟡 Partially covered.
// ══════════════════════════════════════════════════════════════════════════
test.describe('TC_APP_001 — Add candidate via Resume File Upload (Applications flow)', () => {

  test('Upload DOCX → Send Now → count +1 → Bulk Created toast', async ({
    page, browser, loggedInPage,
  }) => {
    const candidatesPage = new CandidatesPage(page);
    const docxPath       = path.resolve(PD, 'Advanced_DotNet_Resume_7.docx');
    const docxName       = 'Advanced_DotNet_Resume_7.docx';

    const { url, initialCount, jobTitle } = await openCandidates(candidatesPage);

    // ── upload + send now ──────────────────────────────────────────────
    await test.step(`Upload ${docxName} and send now`, async () => {
      await candidatesPage.addCandidateByResume(docxPath, 'now');
    });

    // ── verify ─────────────────────────────────────────────────────────
    await test.step('Verify count increased by 1', async () => {
      await candidatesPage.navigateToUrl(url);
      await candidatesPage.assertCandidateCount(initialCount + 1);
    });

    await test.step('Verify Bulk Created toast', async () => {
      await candidatesPage.assertBulkCreatedToast(1);
    });
  });

  test('Upload DOCX → Send Later → count +1 (no email check)', async ({
    page, loggedInPage,
  }) => {
    const candidatesPage = new CandidatesPage(page);
    const docxPath       = path.resolve(PD, 'Advanced_DotNet_Resume_7.docx');

    const { url, initialCount } = await openCandidates(candidatesPage);

    await test.step('Upload DOCX and send later', async () => {
      await candidatesPage.addCandidateByResume(docxPath, 'later');
    });

    await test.step('Verify count increased by 1', async () => {
      await candidatesPage.navigateToUrl(url);
      await candidatesPage.assertCandidateCount(initialCount + 1);
    });
  });
});

