// ══════════════════════════════════════════════════════════════════════════
//  TC_APP_006 — Upload an unsupported file (not in the supported list)
//  Supported types per the app banner: PDF, DOC, DOCX, TXT, RTF.
//  We use a .zip (not in that list) so the "Unsupported files" banner
//  appears and no candidate is created.
// ══════════════════════════════════════════════════════════════════════════
test.describe('TC_APP_006 — Upload an unsupported (non-resume) file', () => {

  test('Upload .zip file → "Unsupported files" banner → count unchanged', async ({
    page, loggedInPage,
  }) => {
    const candidatesPage = new CandidatesPage(page);
    const zipPath        = path.resolve(PD, 'invalid_file.zip');

    const { url, initialCount } = await openCandidates(candidatesPage);

    await test.step('Upload unsupported .zip file through the full flow', async () => {
      try {
        await candidatesPage.addCandidateByFileUpload([zipPath], 'now');
      } catch (err) {
        console.log(`File-upload step threw (likely rejection): ${err.message}`);
      }
    });

    await test.step('Verify candidate count did NOT increase', async () => {
      await candidatesPage.navigateToUrl(url);
      const afterCount = await candidatesPage.getCandidateCount();
      expect(afterCount).toBe(initialCount,
        `Expected count to remain ${initialCount} but got ${afterCount}`);
    });

    await test.step('Capture any error message shown by the UI', async () => {
      const msg = await candidatesPage.getErrorMessage(8_000);
      if (msg) {
        console.log(`UI error message: ${msg}`);
      }
    });
  });
});
